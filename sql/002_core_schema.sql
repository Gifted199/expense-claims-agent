-- 002: core business schema.
-- Money: GBP, numeric(10,2). Times: timestamptz.
-- Identity columns are BY DEFAULT so the seed can insert fixed IDs for reproducibility.

-- Departments: teams, each with a cost centre that spending is charged to.
CREATE TABLE IF NOT EXISTS departments (
    department_id  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           text NOT NULL UNIQUE CHECK (code ~ '^[A-Z]{2,6}$'),
    name           text NOT NULL UNIQUE,
    cost_centre    text NOT NULL UNIQUE
);

-- Employees: grade decides which limits apply; manager_id routes approvals.
CREATE TABLE IF NOT EXISTS employees (
    employee_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code  text NOT NULL UNIQUE CHECK (employee_code ~ '^E[0-9]{4}$'),
    full_name      text NOT NULL CHECK (length(full_name) BETWEEN 1 AND 200),
    email          text NOT NULL UNIQUE CHECK (email LIKE '%_@_%'),
    department_id  smallint NOT NULL REFERENCES departments (department_id),
    grade          text NOT NULL CHECK (grade IN ('associate', 'senior', 'director')),
    manager_id     integer REFERENCES employees (employee_id),
    home_currency  char(3) NOT NULL DEFAULT 'GBP' CHECK (home_currency ~ '^[A-Z]{3}$'),
    hired_on       date NOT NULL,
    is_active      boolean NOT NULL DEFAULT true,
    CONSTRAINT employees_not_own_manager CHECK (manager_id IS NULL OR manager_id <> employee_id)
);
CREATE INDEX IF NOT EXISTS employees_manager_idx ON employees (manager_id);
CREATE INDEX IF NOT EXISTS employees_department_idx ON employees (department_id);

-- Expense categories: fixed list so categories don't drift into free text.
CREATE TABLE IF NOT EXISTS expense_categories (
    category_code          text PRIMARY KEY CHECK (category_code ~ '^[a-z_]+$'),
    name                   text NOT NULL UNIQUE,
    description            text NOT NULL,
    is_travel              boolean NOT NULL,
    receipt_required_over  numeric(10,2) NOT NULL CHECK (receipt_required_over >= 0)
);

-- Policy limits: per category x grade, per claim and per calendar month (GBP).
CREATE TABLE IF NOT EXISTS policy_limits (
    category_code    text NOT NULL REFERENCES expense_categories (category_code),
    grade            text NOT NULL CHECK (grade IN ('associate', 'senior', 'director')),
    per_claim_limit  numeric(10,2) NOT NULL CHECK (per_claim_limit > 0),
    monthly_limit    numeric(10,2) NOT NULL,
    currency         char(3) NOT NULL DEFAULT 'GBP' CHECK (currency ~ '^[A-Z]{3}$'),
    effective_from   date NOT NULL DEFAULT DATE '2025-01-01',
    PRIMARY KEY (category_code, grade),
    CONSTRAINT policy_limits_monthly_ge_claim CHECK (monthly_limit >= per_claim_limit)
);

-- Claims: one row per expense. anomaly_score is filled by the ML model (Phase 2).
CREATE TABLE IF NOT EXISTS claims (
    claim_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_ref       text NOT NULL UNIQUE,
    employee_id     integer NOT NULL REFERENCES employees (employee_id),
    category_code   text NOT NULL REFERENCES expense_categories (category_code),
    amount          numeric(10,2) NOT NULL CHECK (amount > 0),
    currency        char(3) NOT NULL DEFAULT 'GBP' CHECK (currency ~ '^[A-Z]{3}$'),
    incurred_at     timestamptz NOT NULL,
    submitted_at    timestamptz NOT NULL DEFAULT now(),
    merchant        text NOT NULL CHECK (length(merchant) BETWEEN 1 AND 200),
    description     text NOT NULL CHECK (length(description) <= 1000),
    status          text NOT NULL DEFAULT 'submitted'
                        CHECK (status IN ('submitted', 'approved', 'pending_manager', 'rejected')),
    receipt_s3_key  text CHECK (receipt_s3_key IS NULL OR length(receipt_s3_key) <= 1024),
    anomaly_score   real CHECK (anomaly_score IS NULL OR anomaly_score BETWEEN 0 AND 1),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT claims_incurred_before_submitted CHECK (incurred_at <= submitted_at)
);
CREATE INDEX IF NOT EXISTS claims_employee_incurred_idx ON claims (employee_id, incurred_at);
CREATE INDEX IF NOT EXISTS claims_category_incurred_idx ON claims (category_code, incurred_at);
CREATE INDEX IF NOT EXISTS claims_duplicate_lookup_idx ON claims (employee_id, merchant, amount);
CREATE INDEX IF NOT EXISTS claims_pending_manager_idx ON claims (submitted_at)
    WHERE status = 'pending_manager';

-- Approvals: every decision on a claim, by the system (auto) or a human manager.
CREATE TABLE IF NOT EXISTS approvals (
    approval_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id      bigint NOT NULL REFERENCES claims (claim_id),
    decider_type  text NOT NULL CHECK (decider_type IN ('system', 'manager')),
    decided_by    integer REFERENCES employees (employee_id),
    decision      text NOT NULL CHECK (decision IN ('approved', 'rejected')),
    reason        text NOT NULL CHECK (length(reason) BETWEEN 1 AND 1000),
    requested_at  timestamptz NOT NULL,
    decided_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT approvals_manager_has_decider
        CHECK ((decider_type = 'manager') = (decided_by IS NOT NULL)),
    CONSTRAINT approvals_decided_after_requested CHECK (decided_at >= requested_at)
);
CREATE INDEX IF NOT EXISTS approvals_claim_idx ON approvals (claim_id);
CREATE INDEX IF NOT EXISTS approvals_decided_by_idx ON approvals (decided_by);

-- Audit log: append-only trail of who did what (app_writer gets INSERT only, see 004).
CREATE TABLE IF NOT EXISTS audit_log (
    audit_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at        timestamptz NOT NULL DEFAULT now(),
    actor_type         text NOT NULL CHECK (actor_type IN ('employee', 'manager', 'system', 'agent')),
    actor_employee_id  integer REFERENCES employees (employee_id),
    action             text NOT NULL CHECK (length(action) BETWEEN 1 AND 100),
    entity_type        text NOT NULL CHECK (length(entity_type) BETWEEN 1 AND 50),
    entity_id          text,
    details            jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS audit_log_entity_idx ON audit_log (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS audit_log_occurred_idx ON audit_log (occurred_at);
CREATE INDEX IF NOT EXISTS audit_log_actor_idx ON audit_log (actor_employee_id);

-- Nobody may approve or reject their own claim. A CHECK can't look at another table,
-- so this is a trigger: enforced by the database, not left to app code.
CREATE OR REPLACE FUNCTION prevent_self_approval() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path = public, pg_temp
AS $$
BEGIN
    IF NEW.decided_by IS NOT NULL
       AND NEW.decided_by = (SELECT c.employee_id FROM claims c WHERE c.claim_id = NEW.claim_id) THEN
        RAISE EXCEPTION 'employee % cannot decide their own claim %', NEW.decided_by, NEW.claim_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER approvals_no_self_approval
    BEFORE INSERT OR UPDATE ON approvals
    FOR EACH ROW EXECUTE FUNCTION prevent_self_approval();

-- Keep claims.updated_at honest.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path = public, pg_temp
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER claims_set_updated_at
    BEFORE UPDATE ON claims
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
